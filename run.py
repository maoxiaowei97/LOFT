def run_configured_evaluation(model, test_loader, std, mean, use_nni, nsample, results_file, base_savename):
    steps = int(model.config["flow_matching"].get("inference_steps", 2))
    logging.info("\n" + "=" * 50)
    logging.info(f"[Final Evaluation] Running {steps}-step inference.")
    logging.info("=" * 50)

    model.config["flow_matching"]["inference_steps"] = str(steps)

    tensor_save_name = f"evaluation_tensors_{base_savename}_NFE{steps}.pth"
    tensor_save_path = os.path.join(args.output_root, "results", tensor_save_name)
    trace_file = args.trace_file
    if trace_file and not os.path.isabs(trace_file):
        trace_file = os.path.join(args.output_root, trace_file)

    evaluate(
        model,
        test_loader,
        std, mean, use_nni,
        nsample=nsample,
        results_file=results_file,
        tensor_save_path=tensor_save_path,
        trace_file=trace_file,
        trace_batches=args.trace_batches,
        trace_samples=args.trace_samples,
    )


