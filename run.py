def get_cond_epoch_tag(cond_path):
    if not cond_path:
        return "from_no_pretrain"
    basename = os.path.basename(cond_path)
    match = re.search(r"(?:^|_)epoch(\d+)(?:_|\.|$)", basename)
    if match is None:
        match = re.search(r"(?:^|_)ep(\d+)(?:_|\.|$)", basename)
    if match:
        return f"from_epoch{match.group(1)}"
    return "from_unknown_epoch"


def resolve_device(requested_device):

    try:
        device = torch.device(requested_device)
    except (TypeError, RuntimeError) as exc:
        raise ValueError(f"Invalid --device value: {requested_device!r}") from exc

    if device.type != "cuda":
        return str(device)

    cuda_warnings = []
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        cuda_available = torch.cuda.is_available()
        device_count = torch.cuda.device_count() if cuda_available else 0
    cuda_warnings = [str(item.message) for item in caught]

    if not cuda_available:
        details = [
            f"Requested CUDA device {requested_device!r}, but PyTorch cannot use CUDA.",
            f"torch={torch.__version__}, torch.version.cuda={torch.version.cuda}",
        ]
        if cuda_warnings:
            details.append("CUDA init warning: " + " | ".join(cuda_warnings))
        details.extend(
            [
                "Please check `nvidia-smi` and make sure the NVIDIA driver is running.",
                "If the driver is older than this PyTorch CUDA build, either update the driver or use a PyTorch build compiled for the installed driver.",
                "For a CPU-only smoke test, pass `--device cpu`.",
            ]
        )
        raise RuntimeError("\n".join(details))

    requested_index = device.index if device.index is not None else 0
    if requested_index >= device_count:
        raise RuntimeError(
            f"Requested {requested_device!r}, but PyTorch sees only {device_count} CUDA device(s). "
            f"Use a device index in [0, {device_count - 1}] or set CUDA_VISIBLE_DEVICES appropriately."
        )

    return str(device)


